    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
   int selectedRow = tblCustomers.getSelectedRow();
        
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, 
                "Por favor, seleccione un cliente de la tabla antes de presionar Eliminar.", 
                "Selección Requerida", 
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        String ruc = tableModel.getValueAt(selectedRow, 0).toString();
        String name = tableModel.getValueAt(selectedRow, 1).toString();
        
        int confirm = JOptionPane.showConfirmDialog(this, 
            "¿Está seguro de que desea eliminar permanentemente al cliente:\n" + name + " (RUC: " + ruc + ")?", 
            "Confirmar Eliminación", 
            JOptionPane.YES_NO_OPTION, 
            JOptionPane.WARNING_MESSAGE);
            
        if (confirm == JOptionPane.YES_OPTION) {
            try {
                com.mongodb.client.MongoDatabase database = ec.edu.espe.Billing.utils.MongoDBConnection.getDatabase();
                com.mongodb.client.MongoCollection<org.bson.Document> collection = database.getCollection("Customer");
                
                collection.deleteOne(com.mongodb.client.model.Filters.eq("ruc", ruc));
                
                JOptionPane.showMessageDialog(this, 
                    "¡Cliente eliminado correctamente de la base de datos!", 
                    "Eliminación Exitosa", 
                    JOptionPane.INFORMATION_MESSAGE);
                
                txtSearchRuc.setText("");
                loadCustomersFromMongoDB("");
                
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, 
                    "Error al intentar eliminar de la base de datos: " + e.getMessage(), 
                    "Error", 
                    JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

