    private void loadCustomersFromMongoDB(String filterRuc) {
        tableModel.setRowCount(0); 
        
        try {
            MongoDatabase database = ec.edu.espe.Billing.utils.MongoDBConnection.getDatabase();
            MongoCollection<Document> collection = database.getCollection("Customer");
            
            Iterable<Document> documents;
            if (!filterRuc.isEmpty()) {
                
                documents = collection.find(Filters.regex("ruc", filterRuc, "i"));
            } else {
                documents = collection.find();
            }
            
            
            for (Document doc : documents) {
                Object[] rowData = {
                    doc.getString("ruc"),
                    doc.getString("name"),
                    doc.getString("address"),
                    doc.getString("email")
                };
                tableModel.addRow(rowData);
            }
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, 
                "Error al cargar clientes de MongoDB: " + e.getMessage(), 
                "Error de Base de Datos", 
                JOptionPane.ERROR_MESSAGE);
        }
    }

