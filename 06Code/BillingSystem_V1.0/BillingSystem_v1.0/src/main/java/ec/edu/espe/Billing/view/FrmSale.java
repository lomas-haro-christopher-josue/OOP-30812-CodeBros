    private void btnRegisterSaleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterSaleActionPerformed
    
        String invoiceNum = txtInvoiceNumber.getText().trim();
        String cashier = cmbCashier.getSelectedItem().toString();
        
        int customerIndex = cmbCustomer.getSelectedIndex();
        int productIndex = cmbProduct.getSelectedIndex();
        int quantity = (Integer) spnQuantity.getValue();
        String paymentMethod = cmbPaymentMethod.getSelectedItem().toString();
        
   
        if (invoiceNum.isEmpty() || customerIndex <= 0 || productIndex <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Por favor, complete el número de factura, seleccione un cliente y un producto antes de procesar.", 
                "Datos Incompletos", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        String customerRuc = customerIds.get(customerIndex);
        String productId = productIds.get(productIndex);
        
        try {
            com.mongodb.client.MongoDatabase database = ec.edu.espe.Billing.utils.MongoDBConnection.getDatabase();
            com.mongodb.client.MongoCollection<org.bson.Document> productCollection = database.getCollection("Product");
            com.mongodb.client.MongoCollection<org.bson.Document> saleCollection = database.getCollection("Sales");
            
            
            org.bson.Document productDoc = productCollection.find(com.mongodb.client.model.Filters.eq("productId", productId)).first();
            if (productDoc == null) {
                javax.swing.JOptionPane.showMessageDialog(this, "El producto seleccionado ya no existe en la base de datos.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            int currentStock = productDoc.getInteger("stock");
            String productName = productDoc.getString("name");
            double price = productDoc.getDouble("price");
            
            
            if (quantity > currentStock) {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "No se puede realizar la venta.\nEl producto " + productName + " solo cuenta con " + currentStock + " unidades en stock.", 
                    "Stock Insuficiente", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            
            double totalSales = price * quantity;
            double cashReceived = 0.0;

           
            if (paymentMethod.equalsIgnoreCase("Efectivo")) {
                try {
                    String cashText = txtCashReceived.getText().trim();
                    if (!cashText.isEmpty()) {
                        cashReceived = Double.parseDouble(cashText);
                        
                        
                        if (cashReceived < totalSales) {
                            javax.swing.JOptionPane.showMessageDialog(this, 
                                "El efectivo recibido ($" + cashReceived + ") es menor al total a pagar ($" + totalSales + ").", 
                                "Efectivo Insuficiente", 
                                javax.swing.JOptionPane.WARNING_MESSAGE);
                            return;
                        }
                    } else {
                        cashReceived = totalSales; // Si el cajero lo dejó vacío, asumimos pago exacto
                    }
                } catch (NumberFormatException nfe) {
                    cashReceived = totalSales; 
                }
            } else {
            
                cashReceived = totalSales;
            }
            
            
            int newStock = currentStock - quantity;
            productCollection.updateOne(com.mongodb.client.model.Filters.eq("productId", productId), 
                                        com.mongodb.client.model.Updates.set("stock", newStock));
            
            
            org.bson.Document saleDoc = new org.bson.Document("invoiceNumber", invoiceNum)
                    .append("cashier", cashier)
                    .append("customerRuc", customerRuc)
                    .append("productId", productId)
                    .append("productName", productName)
                    .append("quantity", quantity)
                    .append("total", totalSales)
                    .append("paymentMethod", paymentMethod)
                    .append("cashReceived", cashReceived) 
                    .append("timestamp", new java.util.Date()); // Clave para jalar la ÚLTIMA factura
                    
            saleCollection.insertOne(saleDoc);
            
            javax.swing.JOptionPane.showMessageDialog(this, 
                "¡Venta Registrada con Éxito!\nEl stock global ha sido descontado correctamente.", 
                "Facturación Exitosa", 
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
            
            
            loadProductsByCategory();
            
            
            txtInvoiceNumber.setText("");
            if (txtCashReceived.isEnabled()) {
                txtCashReceived.setText("");
            } else {
                txtCashReceived.setText("0.0");
            }
            spnQuantity.setValue(1);
            
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Error crítico al procesar la venta en la base de datos: " + e.getMessage(), 
                "Error de Transacción", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnRegisterSaleActionPerformed

