private void loadCustomersFromMongoDB() {
        cmbCustomer.removeAllItems();
        customerIds.clear();
        
        cmbCustomer.addItem("Seleccione un cliente...");
        customerIds.add(""); 
        
        try {
            MongoDatabase database = ec.edu.espe.Billing.utils.MongoDBConnection.getDatabase();
            MongoCollection<Document> collection = database.getCollection("Customer");
            
            for (Document doc : collection.find()) {
                String ruc = doc.getString("ruc");
                String name = doc.getString("name");
                
                cmbCustomer.addItem(name + " (RUC: " + ruc + ")");
                customerIds.add(ruc); 
            }
        } catch (Exception e) {
            System.out.println("Error al cargar clientes: " + e.getMessage());
        }
    }

private void loadProductsByCategory() {
        cmbProduct.removeAllItems();
        productIds.clear();
        
        cmbProduct.addItem("Seleccione un producto...");
        productIds.add(""); 
        
        if (cmbCategoryFilter.getSelectedIndex() == 0) {
            return;
        }
        
        String selectedCategory = cmbCategoryFilter.getSelectedItem().toString();
        
        try {
            MongoDatabase database = ec.edu.espe.Billing.utils.MongoDBConnection.getDatabase();
            MongoCollection<Document> collection = database.getCollection("Product");
            
            
            for (Document doc : collection.find(Filters.eq("category", selectedCategory))) {
                String id = doc.getString("productId");
                String name = doc.getString("name");
                int stock = doc.getInteger("stock");
                
                
                cmbProduct.addItem(name + " (" + stock + " u. disponibles)");
                productIds.add(id); 
            }
        } catch (Exception e) {
            System.out.println("Error al cargar productos filrados: " + e.getMessage());
        }
    }

