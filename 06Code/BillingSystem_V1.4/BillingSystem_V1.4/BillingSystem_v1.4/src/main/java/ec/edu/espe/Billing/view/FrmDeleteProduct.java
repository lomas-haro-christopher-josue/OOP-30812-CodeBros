    private void btnDeleteProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteProductActionPerformed
    int selectedRow = tblProducts.getSelectedRow();
        
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, 
                "Por favor, seleccione un producto de la tabla para darlo de baja.", 
                "Selección Requerida", 
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        
        String productId = tableModel.getValueAt(selectedRow, 0).toString();
        String productName = tableModel.getValueAt(selectedRow, 1).toString();
        
        int confirm = JOptionPane.showConfirmDialog(this, 
            "¿Seguro que desea eliminar permanentemente el producto del inventario?\n" + productName + " (ID: " + productId + ")", 
            "Confirmar Baja de Producto", 
            JOptionPane.YES_NO_OPTION, 
            JOptionPane.WARNING_MESSAGE);
            
        if (confirm == JOptionPane.YES_OPTION) {
            try {
                MongoDatabase database = ec.edu.espe.Billing.utils.MongoDBConnection.getDatabase();
                MongoCollection<Document> collection = database.getCollection("Product");
                
               
                collection.deleteOne(Filters.eq("productId", productId));
                
                JOptionPane.showMessageDialog(this, 
                    "El producto ha sido eliminado del inventario con éxito.", 
                    "Eliminación Exitosa", 
                    JOptionPane.INFORMATION_MESSAGE);
                
               
                loadProductsFromMongoDB();
                
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, 
                    "Error al intentar eliminar de la base de datos: " + e.getMessage(), 
                    "Error", 
                    JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnDeleteProductActionPerformed

