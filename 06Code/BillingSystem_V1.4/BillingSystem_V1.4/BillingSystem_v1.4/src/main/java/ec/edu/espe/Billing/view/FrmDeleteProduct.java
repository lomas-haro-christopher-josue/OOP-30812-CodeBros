    private void loadProductsFromMongoDB() {
        tableModel.setRowCount(0); 
        
        
        if (cmbDeleteCategory.getSelectedIndex() == 0) {
            return;
        }
        
        String selectedCategory = cmbDeleteCategory.getSelectedItem().toString();
        String searchName = txtSearchProductName.getText().trim();
        
        try {
            MongoDatabase database = ec.edu.espe.Billing.utils.MongoDBConnection.getDatabase();
            MongoCollection<Document> collection = database.getCollection("Product");
            
            
            Bson filter = Filters.eq("category", selectedCategory);
            
            
            if (!searchName.isEmpty()) {
            
                Bson nameFilter = Filters.regex("name", searchName, "i");
                filter = Filters.and(filter, nameFilter);
            }
            
            Iterable<Document> documents = collection.find(filter);
            
            
            for (Document doc : documents) {
                Object[] rowData = {
                    doc.getString("productId"),
                    doc.getString("name"),
                    doc.getString("category"),
                    doc.getDouble("price"),
                    doc.getInteger("stock")
                };
                tableModel.addRow(rowData);
            }
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, 
                "Error al procesar el inventario en MongoDB: " + e.getMessage(), 
                "Error", 
                JOptionPane.ERROR_MESSAGE);
        }
    }
    
    

