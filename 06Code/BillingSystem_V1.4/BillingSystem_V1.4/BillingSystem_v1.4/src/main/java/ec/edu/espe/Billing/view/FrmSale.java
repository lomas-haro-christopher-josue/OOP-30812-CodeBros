    private void generateNextInvoiceNumber() {
   try {
        MongoDatabase database = ec.edu.espe.Billing.utils.MongoDBConnection.getDatabase();
        MongoCollection<Document> salesCollection = database.getCollection("Sales");

        int maxInvoiceNumber = 0;

        
        for (Document doc : salesCollection.find()) {
            if (doc.containsKey("invoiceNumber")) {
                Object val = doc.get("invoiceNumber");
                int currentNum = 0;

                if (val instanceof String) {
                    try {
                        currentNum = Integer.parseInt((String) val);
                    } catch (NumberFormatException e) {
                        currentNum = 0;
                    }
                } else if (val instanceof Number) {
                    currentNum = ((Number) val).intValue();
                }

                if (currentNum > maxInvoiceNumber) {
                    maxInvoiceNumber = currentNum;
                }
            }
        }

      
        int nextNumber = maxInvoiceNumber + 1;

       
        String formattedInvoiceNumber = String.format("%08d", nextNumber);
        txtInvoiceNumber.setText(formattedInvoiceNumber);

    } catch (Exception e) {
        System.out.println("Error al generar el número de factura: " + e.getMessage());
        txtInvoiceNumber.setText("00000001");
    }
    }

    private void calculateTotal() {
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    double grandTotal = 0.0;
if (model.getRowCount() == 0) {
        lblTotalAmount.setText("Total a Pagar: $0.00");
        return;
    }

   
    for (int i = 0; i < model.getRowCount(); i++) {
        try {
            Object value = model.getValueAt(i, 4);
            if (value != null) {
                String cleanValue = value.toString().replace("$", "").replace(",", ".").trim();
                grandTotal += Double.parseDouble(cleanValue);
            }
        } catch (NumberFormatException e) {
          
        }
    }

  
    lblTotalAmount.setText(String.format("Total a Pagar: $%.2f", grandTotal));
    }
