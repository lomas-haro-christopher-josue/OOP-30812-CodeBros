    private void btnRegisterSaleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterSaleActionPerformed
String invoiceNum = txtInvoiceNumber.getText().trim();
    int customerIndex = cmbCustomer.getSelectedIndex();
    String paymentMethod = cmbPaymentMethod.getSelectedItem() != null ? cmbPaymentMethod.getSelectedItem().toString() : "";

 
    if (invoiceNum.isEmpty() || customerIndex <= 0) {
        JOptionPane.showMessageDialog(this, 
            "Por favor, asegúrese de tener un número de factura y un cliente seleccionado.", 
            "Datos Incompletos", JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (jTable1.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, 
            "Debe agregar al menos un producto a la tabla antes de registrar la venta.", 
            "Tabla Vacía", JOptionPane.WARNING_MESSAGE);
        return;
    }

   
    String selectedCustomerText = cmbCustomer.getSelectedItem().toString();
    String customerRuc = selectedCustomerText.split("-")[0].trim();

    
    String cashier = "Desconocido";
    if (cmbCashier.getSelectedItem() != null) {
        cashier = cmbCashier.getSelectedItem().toString();
    }

   
    javax.swing.table.DefaultTableModel tableModel = (javax.swing.table.DefaultTableModel) jTable1.getModel();
    double totalSales = 0.0;
    for (int i = 0; i < tableModel.getRowCount(); i++) {
        totalSales += Double.parseDouble(tableModel.getValueAt(i, 4).toString());
    }
    totalSales = Math.round(totalSales * 100.0) / 100.0;

    
    double cashReceived = totalSales;
    if (paymentMethod.equalsIgnoreCase("Efectivo")) {
        String cashText = txtCashReceived.getText().trim();
        if (cashText.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Por favor ingrese el monto en efectivo recibido.", 
                "Efectivo Requerido", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            cashReceived = Double.parseDouble(cashText);
            if (cashReceived < totalSales) {
                JOptionPane.showMessageDialog(this, 
                    "El efectivo recibido ($" + cashReceived + ") es menor al total a pagar ($" + totalSales + ").", 
                    "Efectivo Insuficiente", JOptionPane.WARNING_MESSAGE);
                return;
            }
        } catch (NumberFormatException nfe) {
            JOptionPane.showMessageDialog(this, 
                "Ingrese un valor numérico válido para el efectivo recibido.", 
                "Error de Formato", JOptionPane.ERROR_MESSAGE);
            return;
        }
        tableModel.setRowCount(0);
        txtCashReceived.setText("");
        lblTotalAmount.setText("Total a Pagar: $0.00");
        calculateTotal();
        lblTotalAmount.repaint();
    }

    
    try {
        MongoDatabase database = ec.edu.espe.Billing.utils.MongoDBConnection.getDatabase();
        MongoCollection<Document> productCollection = database.getCollection("Product");
        MongoCollection<Document> saleCollection = database.getCollection("Sales");
        MongoCollection<Document> invoiceCollection = database.getCollection("Invoices");

        java.util.Date currentDate = new java.util.Date();

        
        for (int i = 0; i < tableModel.getRowCount(); i++) {
            String pId = tableModel.getValueAt(i, 0).toString();
            String pName = tableModel.getValueAt(i, 1).toString();
            int pQty = Integer.parseInt(tableModel.getValueAt(i, 3).toString());
            double pSubtotal = Double.parseDouble(tableModel.getValueAt(i, 4).toString());

           
            Document productDoc = productCollection.find(Filters.eq("productId", pId)).first();
            if (productDoc != null) {
                int currentStock = productDoc.getInteger("stock", 0);
                productCollection.updateOne(Filters.eq("productId", pId), Updates.set("stock", currentStock - pQty));
            }

            
            Document saleDoc = new Document("invoiceNumber", invoiceNum)
                    .append("cashier", cashier)
                    .append("customerRuc", customerRuc)
                    .append("productId", pId)
                    .append("productName", pName)
                    .append("quantity", pQty)
                    .append("total", pSubtotal)
                    .append("paymentMethod", paymentMethod)
                    .append("cashReceived", cashReceived)
                    .append("timestamp", currentDate);

            saleCollection.insertOne(saleDoc);
        }

        
        Document invoiceDoc = new Document("invoiceNumber", invoiceNum)
                .append("customerRuc", customerRuc)
                .append("cashier", cashier)
                .append("totalAmount", totalSales)
                .append("paymentMethod", paymentMethod)
                .append("cashReceived", cashReceived)
                .append("date", currentDate);

        invoiceCollection.insertOne(invoiceDoc);

        
        JOptionPane.showMessageDialog(this, 
            "Venta registrada con éxito.\nFactura Nro: " + invoiceNum + "\nTotal: $" + String.format("%.2f", totalSales), 
            "Éxito", JOptionPane.INFORMATION_MESSAGE);

        tableModel.setRowCount(0);
        txtCashReceived.setText("");
        spnQuantity.setValue(1);
        
        if (cmbCustomer.getItemCount() > 0) cmbCustomer.setSelectedIndex(0);
        if (cmbCategoryFilter.getItemCount() > 0) cmbCategoryFilter.setSelectedIndex(0);
        
        
        generateNextInvoiceNumber();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, 
            "Error al registrar la venta en la base de datos: " + e.getMessage(), 
            "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnRegisterSaleActionPerformed

