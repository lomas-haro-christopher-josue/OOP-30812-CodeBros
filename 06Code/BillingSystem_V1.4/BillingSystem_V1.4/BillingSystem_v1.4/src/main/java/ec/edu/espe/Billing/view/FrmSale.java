    private void btnAddProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddProductActionPerformed
        int productIndex = cmbProduct.getSelectedIndex();
    
   
    if (productIndex <= 0) {
        JOptionPane.showMessageDialog(this, 
            "Por favor, seleccione un producto válido.", 
            "Producto No Seleccionado", JOptionPane.WARNING_MESSAGE);
        return;
    }

    
    int quantity = Integer.parseInt(spnQuantity.getValue().toString());
    if (quantity <= 0) {
        JOptionPane.showMessageDialog(this, 
            "La cantidad debe ser mayor a 0.", 
            "Cantidad Inválida", JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        String productId = productIds.get(productIndex);
        
       
        MongoDatabase database = ec.edu.espe.Billing.utils.MongoDBConnection.getDatabase();
        MongoCollection<Document> collection = database.getCollection("Product");
        Document productDoc = collection.find(Filters.eq("productId", productId)).first();

        if (productDoc != null) {
            String name = productDoc.getString("name");
            double price = ((Number) productDoc.get("price")).doubleValue();
            int currentStock = productDoc.getInteger("stock", 0);

            if (quantity > currentStock) {
                JOptionPane.showMessageDialog(this, 
                    "Stock insuficiente. Solo quedan " + currentStock + " unidades disponibles.", 
                    "Stock Insuficiente", JOptionPane.WARNING_MESSAGE);
                return;
            }

           
            double subtotalRaw = price * quantity;
            double subtotal = Math.round(subtotalRaw * 100.0) / 100.0;

           
            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
            model.addRow(new Object[]{productId, name, price, quantity, subtotal});
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, 
            "Error al agregar producto: " + e.getMessage(), 
            "Error", JOptionPane.ERROR_MESSAGE);
    }
    calculateTotal();
    }//GEN-LAST:event_btnAddProductActionPerformed

